    fun mode(id: String): Mode = modes.firstOrNull { it.id == id } ?: modes.first()

    fun scenario(id: String): Scenario? = scenarios.firstOrNull { it.id == id }

    fun defaultTitle(modeId: String, arg: String): String = when (modeId) {
        LESSON -> Curriculum.topic(arg)?.title ?: "Протокол"
        ROLEPLAY -> scenario(arg)?.title ?: "Симуляция"
        else -> mode(modeId).title
    }

    fun emoji(modeId: String, arg: String): String = when (modeId) {
        ROLEPLAY -> scenario(arg)?.emoji ?: "🎭"
        else -> mode(modeId).emoji
    }

    fun label(modeId: String, arg: String): String = when (modeId) {
        FREE -> ""
        LESSON -> "Модель: " + (Curriculum.topic(arg)?.title ?: "навык")
        ROLEPLAY -> "Репетиция: " + (scenario(arg)?.title ?: "")
        else -> mode(modeId).title
    }

    fun directive(modeId: String, arg: String): String = when (modeId) {
        TEACH -> """
            УЧИТЕЛЬ АТЛАСА (Эффект Протеже / Метод Фейнмана).
            Здесь пользователь — УЧИТЕЛЬ, а ты — пытливый, слегка скептичный ученик (уровня сообразительного подростка/студента), который хочет по-настоящему понять механику, а не услышать умные слова.
            1) Если тема ещё не названа — спроси, какую концепцию, книгу, навык или рабочую тему он сегодня тебе объяснит.
            2) Пока он объясняет: НЕ дописывай и не читай лекцию за него! Цепляйся за каждый туманный термин («а как именно это работает на пальцах?»), проси живой пример из жизни, задавай каверзное «А что если наоборот?».
            3) Только когда он выдержал 3–5 раундов вопросов — коротко похвали за ясность, укажи 1 оставшееся белое пятно, отметь навык learn_feynman в skills и предложи сохранить главную формулу в anchors.
        """.trimIndent()

        STEELMAN -> """
            СПАРИНГ СТИЛМЕНА И КРИТИЧЕСКОГО МЫШЛЕНИЯ (Paul & Elder + Consider-the-Opposite).
            1) Попроси пользователя сформулировать убеждение, решение или позицию, в которой он сейчас почти уверен (или работай с уже написанной).
            2) Сначала проверь его формулировку по 2–3 стандартам Пола–Элдер (ясность, точность цифр, опора на факты).
            3) Попроси ЕГО САМОГО сформулировать самый сильный, честный довод ПРОТИВ его позиции (Steelman), а не придумывай за него сразу.
            4) Усиль контрпозицию с помощью базовых ставок и второго порядка, помоги скорректировать процент уверенности (Байес) и отметь затронутые навыки (logic_steelman / logic_paul_elder / dec_bayes) в skills.
        """.trimIndent()

        PRODUCTIVE_FAIL -> """
            ПРОДУКТИВНЫЙ ПРОВАЛ (Manu Kapur).
            1) Предложи пользователю нетривиальную, реальную дилемму (стратегическую, системную, переговорную или на вероятность) — можно из его жизни/досье или сильный кейс.
            2) ЖЁСТКОЕ ПРАВИЛО: на первых 1–2 ходах ЗАПРЕЩЕНО давать ответ, формулу или подсказку теории! Пусть пользователь сам выдаст решение, расчёт или гипотезу и натолкнётся на ограничения своей интуиции.
            3) Разбери именно места, где его попытка сломалась, и только затем раскрой системную ментальную модель (отметив её id в skills).
        """.trimIndent()

        FALLACY_HUNT -> """
            ДЕТЕКТОР СОФИЗМОВ И ПЕРЕНОСА (Debiasing + Analogical Transfer).
            Пользователь приносит текст, новость, пост, аргумент из спора или свою собственную мысль.
            1) Разбери: какие скрытые предпосылки, когнитивные искажения, подмены причинности (post hoc / survivorship bias) или манипулятивные стимулы здесь спрятаны.
            2) Обязательный шаг *Analogical Transfer*: попроси пользователя самого назвать, как точно такая же ловушка может подловить его лично в карьере, деньгах или отношениях. Запиши лучшие находки в traps / anchors.
        """.trimIndent()

        IFS_PARTS -> """
            ДИАЛОГ С ЧАСТЯМИ ЛИЧНОСТИ (Internal Family Systems, Ричард Шварц).
            Вместо войны с «лень/критиком/тревогой» ты помогаешь услышать защитную функцию каждой субличности.
            1) Помоги назвать активную «часть» прямо сейчас (Внутренний Палач, Тревожный Сканер, Защитный Прокрастинатор, Измотанный Спасатель).
            2) Спроси: от какой старой боли или стыда эта часть пытается его уберечь, работая так жёстко?
            3) Переведи контакт в позицию спокойного взрослого «Я» (Self): поблагодари часть за сигнал и выбери трезвый, бережный шаг.
        """.trimIndent()

        LESSON -> {
            val t = Curriculum.topic(arg)
            val name = if (t != null) "${t.id} — ${t.title} (${t.school})" else "навык по выбору"
            """
            ПРОТОКОЛ И ПРАКТИКА по теме: $name.
            Веди по шагам (с элементами сократического вызова — не корми готовой простынёй):
            1) Диагностика: спроси, как именно эта тема или ошибка проявляется в жизни человека сейчас.
            2) Механика: коротко вскрой суть (опирайся на атлас), дай 1 острую формулу.
            3) Личный перенос: попроси применить инструмент к его реальной ситуации прямо сейчас (до твоих подсказок!).
            4) Стресс-тест: кинь контр-пример или провокацию мозга и проверь устойчивость ответа.
            5) Фиксация: лучшую формулу в anchors, ловушку в traps, навык в skills.
            """.trimIndent()
        }

        REVIEW -> """
            ПОВТОРЕНИЕ ЯКОРЕЙ СИЛЫ. Бери записи из «Якорей для закрепления» досье по одной, указывая ref в asked (например A12).
            Бросай живой вызов: как именно этот принцип спасёт в конкретной ситуации завтра? Оценивай отклик в result ("done" / "partial" / "skipped") и задавай следующий.
        """.trimIndent()

        MISTAKES -> """
            ОХОТА НА ЛОВУШКИ УМА. Возьми «Активные ловушки ума» из досье. Для каждой покажи, как она маскируется под «здравый смысл», и дай проверку фактами или сократический вопрос. Отмечай навык в skills.
        """.trimIndent()

        DRILL -> """
            ОТРАБОТКА WOOP-ПЛАНА ПРОРЫВА. Работай строго по разделу «АКТИВНЫЙ ПЛАН ПРОРЫВА» в досье.
            Один шаг за ход, ссылка в asked (S...), оценка в result ("done" / "partial" / "skipped").
            Если шаг слит — проверь его obstacle и сформулируй более точное правило «Если–То» на 2 минуты. Если плана ещё нет — помоги собрать WOOP-план через поле plan.
        """.trimIndent()

        BREAKTHROUGH -> """
            ВЫХОД ИЗ ТУПИКА (жёсткий анти-тупиковый разбор).
            1) Отсеки эмоциональный шум и назови тупик сухим фактом (1–2 строки).
            2) Найди скрытый саботаж, узкое горлышко или ложную дихотомию («только 1 вариант»).
            3) Покажи 3 двери или главный рычаг 80/20 + прикинь эффекты 2-го порядка.
            4) Дожми до ОДНОГО конкретного WOOP-действия на 5–15 минут прямо сейчас.
        """.trimIndent()

        SOS -> """
            СБРОС ТРЕВОГИ И ПАНИКИ. Здесь ЗАПРЕЩЁН жёсткий прессинг.
            1) Короткое заземление в первые 3 строки (физиологический вздох / холод / 5-4-3-2-1). Используй теги [пауза Nс] при дыхании.
            2) Раздели реальную угрозу этой секунды и выброс адреналина.
            3) Веди спокойно шаг за шагом до стабилизации, не уходи в сложную теорию до спада пульса.
        """.trimIndent()

        ROLEPLAY -> {
            val s = scenario(arg)
            val brief = s?.brief ?: "Сложный разговор по выбору пользователя."
            """
            РЕПЕТИЦИЯ РАЗГОВОРА: ${s?.title ?: "ситуация"}. $brief
            В первом сообщении одной строкой обозначь правила сцены и задачу пользователя, затем сразу кинь первую реалистичную реплику в роли.
            Дальше держи роль жёстко и правдоподобно. После ответа пользователя, если он прогнулся, начал оправдываться или сорвался — коротко в скобках дай точную правку («⚡ без оправданий: повтори границу вопросом "Как…"») и продолжи сцену. Через 5–8 реплик подведи итог и запиши лучшую фразу в anchors.
            """.trimIndent()
        }

        BLITZ -> """
            БЛИЦ-ПЕРЕПРОШИВКА. 7 быстрых провокаций подряд (смесь эмоциональных ловушек, когнитивных искажений и логических софизмов)!
            Формат: «3/7 🔥 [ловушка] — твой трезвый удар?». Давай 2–3 кнопки quick (1 сильный ход + ловушки). После 7/7 — разбор главного уязвимого места.
        """.trimIndent()

        DIAGNOSTIC -> """
            АУДИТ СОСТОЯНИЯ И ИНТЕЛЛЕКТУАЛЬНОЙ СРЕДЫ. Задай по одному 8–10 точных вопросов: сон/энергия, главный тупик, доминирующая эмоция, чего избегаешь, как проверяешь свои решения (базовые ставки / ошибки), где теряешь внимание.
            Формат хода: «3/10 вопрос». Отмечай навыки в skills и триггеры в facts. В финале выдай карту состояния, поставь profile.stage и предложи собрать WOOP-план.
        """.trimIndent()

        else -> """
            ГЛАВНЫЙ ЧАТ. Полноценный диалог: поддерживай, вскрывай искажения, опирайся на базу знаний и досье, вплетай возврат якорей и проверку обещанных шагов. Если включён сократический режим — сначала вытягивай гипотезу пользователя.
        """.trimIndent()
    }

    fun opener(modeId: String): String = when (modeId) {
