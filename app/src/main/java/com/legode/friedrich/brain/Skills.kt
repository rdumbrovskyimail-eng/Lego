        Scenario("ask_help", "Попросить о помощи прямо", "🆘", "Ты занятой знакомый или специалист. Пользователь ломает ложную гордость и учится формулировать чёткий, адекватный запрос поддержки."),
        Scenario("imposter", "Синдром самозванца", "🏔️", "Ты скептичный эксперт. Пользователь тренируется не обесценивать собственные навыки и результаты, опираясь на факты."),
        Scenario("future_self", "Диалог с собой через 1 год", "⏳", "Ты — сильная, прошедшая этот кризис версия самого пользователя через 12 месяцев. Говори с ним трезво, тепло и по-деловому."),
