    fun mode(id: String): Mode = modes.firstOrNull { it.id == id } ?: modes.first()

    fun scenario(id: String): Scenario? = scenarios.firstOrNull { it.id == id }

    /** Заголовок новой беседы по режиму. */
    fun defaultTitle(modeId: String, arg: String): String = when (modeId) {
        LESSON -> Curriculum.topic(arg)?.title ?: "Протокол"
        ROLEPLAY -> scenario(arg)?.title ?: "Симуляция"
        else -> mode(modeId).title
    }

    fun emoji(modeId: String, arg: String): String = when (modeId) {
        ROLEPLAY -> scenario(arg)?.emoji ?: "🎭"
        else -> mode(modeId).emoji
    }

    /** Подпись режима для шапки чата. */
    fun label(modeId: String, arg: String): String = when (modeId) {
        FREE -> ""
        LESSON -> "Практика: " + (Curriculum.topic(arg)?.title ?: "навык")
        ROLEPLAY -> "Репетиция: " + (scenario(arg)?.title ?: "")
        else -> mode(modeId).title
    }

    /** Инструкция режима — попадает в раздел «РЕЖИМ БЕСЕДЫ» контекста. */
    fun directive(modeId: String, arg: String): String = when (modeId) {
        LESSON -> {
            val t = Curriculum.topic(arg)
            val name = if (t != null) "${t.id} — ${t.title} (${t.school})" else "навык по выбору"
            """
            ПРОТОКОЛ И ПРАКТИКА по теме: $name.
            Веди по шагам, каждый шаг — отдельный ход:
            1) Диагностика: спроси, как именно эта тема проявляется у человека сейчас (1 короткий вопрос).
            2) Разбор механики: объясни без воды, как устроена психика/философия здесь (опирайся на атлас), дай 1 мощную формулу.
            3) Личная привязка: попроси применить инструмент к его реальной ситуации прямо сейчас.
            4) Проверка устойчивости: предложи 1 провокационную ситуацию/возражение мозга и помоги дать трезвый отпор.
            5) Фиксация: запиши лучшую фразу в anchors, выявленную ловушку в traps, а навык отметь в skills с id темы.
            """.trimIndent()
        }

        REVIEW -> """
            ПОВТОРЕНИЕ ЯКОРЕЙ СИЛЫ. Бери записи из «Якорей для закрепления» досье по одной, указывая ref в asked (например A12).
            Не просто читай фразу — брось человеку жизненный мини-вызов: «Когда завтра накроет старая мысль X, чем ты ей ответишь?» или попроси сформулировать этот принцип своими словами.
            Оцени ответ в result ("done" / "partial" / "skipped"), коротко усиль и задай следующий якорь.
        """.trimIndent()

        MISTAKES -> """
            ОХОТА НА ЛОВУШКИ УМА. Возьми «Активные ловушки ума» из досье. Для каждой:
            1) Покажи, как именно эта ловушка сейчас маскируется под «реальность» или «здравый смысл».
            2) Дай 1 сократический вопрос или поведенческую проверку, чтобы пользователь сам её разоблачил.
            3) Пока человек не выдаст трезвый антидот в 2 ответах подряд — не отпускай ловушку. Отмечай навык в skills.
        """.trimIndent()

        DRILL -> """
            ОТРАБОТКА ПЛАНА ПРОРЫВА. Работай строго по разделу «АКТИВНЫЙ ПЛАН ПРОРЫВА» в досье.
            Один шаг за ход, ссылка в asked (S...), оценка в result ("done" / "partial" / "skipped").
            Если человек буксует и сливает шаг — не ругай абстрактно, а вдвое дроби порог входа и дожимай до выполнения.
            Если активного плана ещё нет — помоги разложить проблему на 5–10 конкретных шагов и сохрани через поле plan.
        """.trimIndent()

        BREAKTHROUGH -> """
            ВЫХОД ИЗ ТУПИКА (жёсткий анти-тупиковый разбор).
            1) Отсеки эмоциональный шум и назови тупик сухим фактом (1–2 строки).
            2) Найди скрытый саботаж, избегание или ложную дихотомию («только 1 вариант»).
            3) Покажи 3 двери или главный рычаг 80/20.
            4) Дожми до ОДНОГО конкретного 5–15 минутного действия прямо сейчас (если просит/уместно — оформи план через поле plan).
        """.trimIndent()

        SOS -> """
            СБРОС ТРЕВОГИ И ПАНИКИ. Здесь ЗАПРЕЩЁН жёсткий прессинг.
            1) Короткое заземление в первые 3 строки (физиологический вздох / холод / 5-4-3-2-1). Используй теги [пауза Nс] при дыхании.
            2) Раздели реальную угрозу этой секунды и выброс адреналина.
            3) Веди спокойно шаг за шагом, пока пульс и голова не выровняются (оценивай mood), не уходи в длинную философию до стабилизации.
        """.trimIndent()

        ROLEPLAY -> {
            val s = scenario(arg)
            val brief = s?.brief ?: "Сложный разговор по выбору пользователя."
            """
            РЕПЕТИЦИЯ РАЗГОВОРА: ${s?.title ?: "ситуация"}. $brief
            В первом сообщении одной строкой обозначь правила сцены и задачу пользователя, затем сразу кинь первую реалистичную реплику в роли.
            Дальше держи роль жёстко и правдоподобно (одна реплика за ход). После ответа пользователя, если он прогнулся, начал оправдываться или взорвался — коротко в скобках укажи точную правку («⚡ без оправданий: обрежь извинения и повтори отказ») и продолжи сцену.
            Через 5–8 реплик выйди из роли: разбери, где держался сильно, где поплыл, и запиши лучшую фразу-границу в anchors.
            """.trimIndent()
        }

        BLITZ -> """
            БЛИЦ-ПЕРЕПРОШИВКА. 7 быстрых провокаций подряд!
            Кидаешь короткую токсичную мысль, отговорку или катастрофу (например: «3/7 🔥 "Я всё равно провалюсь, какой смысл даже пробовать сегодня" — твой трезвый удар по этой мысли?»).
            По возможности давай 2–3 кнопки quick (1 верный сильный ход + 1–2 ловушки). Реагируй коротко (✅ сильно / ⚡ жёстче так: …) и сразу давай следующий раунд. После 7/7 — разбор главного уязвимого места.
        """.trimIndent()

        DIAGNOSTIC -> """
            АУДИТ СОСТОЯНИЯ. Задай по одному 8–10 точных вопросов: уровень сна и энергии тела, где главный тупик сейчас, главная эмоция, чего избегаешь, как говоришь с собой после ошибок, на что опираешься.
            Формат хода: «3/10 вопрос». Отмечай затронутые навыки в skills и триггеры в facts.
            В финале выдай трезвую карту состояния (без приговоров), поставь profile.stage ("истощение" | "спад" | "стабильность" | "сила") и предложи собрать план выхода в поле plan.
        """.trimIndent()

        else -> """
            ГЛАВНЫЙ ЧАТ. Полноценный диалог: поддерживай, вскрывай искажения, опирайся на базу знаний и досье, вплетай возврат якорей и проверку обещанных шагов.
            Если пользователь молчит о делах или тонет в негативе — перехватывай инициативу и предлагай точный рычаг.
        """.trimIndent()
    }

    /** Задача для самого первого сообщения новой беседы (Атлас начинает первым). */
    fun opener(modeId: String): String = when (modeId) {
        FREE -> "Пользователь открыл новый чат. Коротко поприветствуй по времени суток без штампов и спроси прямо, какая задача или состояние сейчас на столе."
        DRILL -> "Пользователь открыл чат отработки плана. Если активный план есть — напомни следующий шаг и спроси статус. Если нет — предложи выгрузить проблему/цель, чтобы разбить её на чёткие шаги."
        else -> "Пользователь только что открыл этот режим. Начни первым: одной строкой задай рамку и сразу сделай первый ход режима."
    }
}
