package com.legode.friedrich.brain

/** Режимы беседы («навыки» Фридриха), ролевые сценки и быстрые команды. */
object Skills {

    data class Mode(
        val id: String,
        val title: String,
        val emoji: String,
        val hint: String,
        val needsTopic: Boolean = false,
        val needsScenario: Boolean = false
    )

    data class Scenario(val id: String, val title: String, val emoji: String, val brief: String)

    data class QuickCommand(val label: String, val text: String)

    const val FREE = "free"
    const val LESSON = "lesson"
    const val REVIEW = "review"
    const val MISTAKES = "mistakes"
    const val DRILL = "drill"
    const val ROLEPLAY = "roleplay"
    const val BLITZ = "blitz"
    const val IMMERSION = "immersion"
    const val PLACEMENT = "placement"
    const val EXAM = "exam"

    val modes: List<Mode> = listOf(
        Mode(FREE, "Свободный чат", "💬", "Болтаем, спрашиваешь что угодно, Friedrich учит по ходу"),
        Mode(LESSON, "Урок по теме", "📚", "Объяснение → примеры → упражнения → мини-тест", needsTopic = true),
        Mode(REVIEW, "Повторение слов", "🃏", "Интервальное повторение твоего словаря"),
        Mode(MISTAKES, "Работа над ошибками", "🩹", "Разбираем твои частые ошибки, пока не уйдут"),
        Mode(ROLEPLAY, "Ролевая сценка", "🎭", "Булочная, врач, вокзал, аренда квартиры…", needsScenario = true),
        Mode(BLITZ, "Блиц", "⚡", "10 быстрых вопросов подряд со счётом"),
        Mode(IMMERSION, "Только немецкий", "🇩🇪", "Friedrich пишет только простым немецким"),
        Mode(PLACEMENT, "Тест уровня", "🧪", "12 вопросов — и Friedrich поймёт, что ты уже знаешь"),
        Mode(EXAM, "Экзамен A1", "🎓", "Тренировка Sprechen и Schreiben в формате Goethe A1"),
        Mode(DRILL, "Отработка списка", "📋", "Твои слова и фразы — до полного освоения")
    )

    val scenarios: List<Scenario> = listOf(
        Scenario("bakery", "В булочной", "🥐", "Ты продавец в булочной (Bäckerei). Ученик покупает хлеб, булочки, кофе. Цены, количество, оплата."),
        Scenario("cafe", "В кафе", "☕", "Ты официант в кафе. Ученик заказывает еду и напитки, просит счёт. Zusammen oder getrennt, stimmt so."),
        Scenario("supermarket", "В супермаркете", "🛒", "Ты сотрудник супермаркета и кассир. Ученик ищет продукты, спрашивает цену, платит картой или наличными."),
        Scenario("clothes", "Магазин одежды", "👕", "Ты продавец одежды. Ученик ищет вещь, спрашивает размер и цвет, примеряет, покупает или отказывается."),
        Scenario("doctor", "У врача", "🩺", "Ты врач (Hausarzt). Ученик пришёл с простой жалобой: расспроси о симптомах, с какого времени, дай рекомендации."),
        Scenario("pharmacy", "В аптеке", "💊", "Ты фармацевт. Ученик просит средство от головной боли, кашля или температуры."),
        Scenario("appointment", "Запись по телефону", "📞", "Ты администратор в клинике на телефоне. Ученик записывается на приём: день, время, перенос."),
        Scenario("station", "На вокзале", "🚆", "Ты кассир на вокзале. Ученик покупает билет: куда, в одну сторону или туда-обратно, время, путь, пересадка."),
        Scenario("directions", "Как пройти?", "🧭", "Ты прохожий. Ученик спрашивает дорогу к вокзалу, аптеке, почте. Объясняй: geradeaus, links, rechts, an der Ampel."),
        Scenario("flat", "Смотрим квартиру", "🏠", "Ты арендодатель (Vermieter). Ученик звонит по объявлению: сколько комнат, аренда, залог, когда посмотреть."),
        Scenario("amt", "В Bürgeramt", "🏛️", "Ты сотрудник Bürgeramt. Ученик делает прописку (Anmeldung): имя, адрес, дата рождения, документы, подпись."),
        Scenario("neighbor", "Знакомство с соседом", "👋", "Ты новый сосед. Small talk: как зовут, откуда, кем работает, семья, хобби."),
        Scenario("course", "Первый день на курсах", "🎒", "Ты однокурсник на курсах немецкого. Знакомство: имя, страна, языки, как давно в Германии, зачем учит немецкий."),
        Scenario("job", "Простое собеседование", "💼", "Ты работодатель. Короткое собеседование: профессия, опыт, когда может начать, график. Только простые вопросы A1.")
    )

    val quickCommands: List<QuickCommand> = listOf(
        QuickCommand("Не понял 🤔", "Не понял. Объясни, пожалуйста, проще и с примером."),
        QuickCommand("Пример", "Дай ещё пару примеров."),
        QuickCommand("Таблица", "Покажи это таблицей."),
        QuickCommand("Переведи", "Переведи на русский твоё последнее сообщение."),
        QuickCommand("Проверь меня", "Проверь меня: задай вопрос по тому, что мы сейчас проходим."),
        QuickCommand("Подсказка", "Дай подсказку, но не ответ."),
        QuickCommand("Сложнее", "Давай чуть сложнее."),
        QuickCommand("Проще", "Давай проще, мне тяжело."),
        QuickCommand("Что дальше?", "Что мне учить дальше? Составь короткий план по моему досье.")
    )

    fun mode(id: String): Mode = modes.firstOrNull { it.id == id } ?: modes.first()

    fun scenario(id: String): Scenario? = scenarios.firstOrNull { it.id == id }

    /** Заголовок новой беседы по режиму. */
    fun defaultTitle(modeId: String, arg: String): String = when (modeId) {
        LESSON -> Curriculum.topic(arg)?.title ?: "Урок"
        ROLEPLAY -> scenario(arg)?.title ?: "Сценка"
        else -> mode(modeId).title
    }

    fun emoji(modeId: String, arg: String): String = when (modeId) {
        ROLEPLAY -> scenario(arg)?.emoji ?: "🎭"
        else -> mode(modeId).emoji
    }

    /** Подпись режима для шапки чата. */
    fun label(modeId: String, arg: String): String = when (modeId) {
        FREE -> ""
        LESSON -> "Урок: " + (Curriculum.topic(arg)?.title ?: "тема")
        ROLEPLAY -> "Сценка: " + (scenario(arg)?.title ?: "")
        else -> mode(modeId).title
    }

    /** Инструкция режима — попадает в раздел «РЕЖИМ БЕСЕДЫ» контекста. */
    fun directive(modeId: String, arg: String): String = when (modeId) {
        LESSON -> {
            val t = Curriculum.topic(arg)
            val name = if (t != null) "${t.id} — ${t.title} (${t.de})" else "тема по выбору ученика"
            """
            УРОК по теме: $name.
            Веди урок по шагам, каждый шаг — отдельный ход переписки:
            1) Зацепка: короткий вопрос, чтобы выяснить, что ученик уже знает по теме.
            2) Объяснение: суть правила простыми словами + мини-таблица или 3–4 примера из справочника. Здесь сообщение может быть длиннее обычного.
            3) Проверка понимания: 2–3 лёгких вопроса по одному.
            4) Практика: 6–8 заданий разного типа по нарастающей, по одному за ход.
            5) Мини-тест: 5 вопросов подряд, в конце счёт и что повторить.
            После мини-теста подведи итог и предложи следующую тему по программе.
            Отмечай прогресс в topics с id темы урока.
            """.trimIndent()
        }

        REVIEW -> """
            ПОВТОРЕНИЕ СЛОВ. Спрашивай слова из раздела «К повторению» досье по одному, каждый раз указывая ref в asked.
            Чередуй: перевод RU→DE, DE→RU, артикль, множественное число, пропуск в предложении.
            Оценивай ответ (result), коротко поправляй, сразу задавай следующее. Каждые 6 слов — промежуточный счёт.
            Если слова к повторению закончились — спрашивай самые слабые и недавние, затем подведи итог.
        """.trimIndent()

        MISTAKES -> """
            РАБОТА НАД ОШИБКАМИ. Возьми «Частые ошибки» из досье. Для каждой: 1) напомни правило одной фразой (не показывая прошлую ошибку как упрёк);
            2) дай 2–3 задания на это правило по одному за ход; 3) когда ученик дважды подряд ответил верно — переходи к следующей ошибке.
            В topics ставь id темы ошибки. В конце — итог: что закрыли, что ещё шатается.
        """.trimIndent()

        DRILL -> """
            ОТРАБОТКА СПИСКА. Работай строго по разделу «АКТИВНЫЙ СПИСОК». Одно задание за ход, ref в asked, оценка в result.
            Если активного списка нет — попроси ученика прислать слова или предложения (текстом, файлом или фото) и создай список через поле list.
        """.trimIndent()

        ROLEPLAY -> {
            val s = scenario(arg)
            val brief = s?.brief ?: "Простая бытовая ситуация по выбору ученика."
            """
            РОЛЕВАЯ СЦЕНКА: ${s?.title ?: "ситуация"}. $brief
            В первом сообщении одной строкой по-русски объясни ситуацию и задачу ученика, затем сразу первая реплика в роли — по-немецки.
            Дальше говори в роли только по-немецки (простые фразы A1), одна реплика за ход. После реплики ученика, если была ошибка, — короткая пометка в скобках по-русски (✏️ …) и продолжение сценки.
            Если ученик застрял — подскажи начало фразы. Сценка длится 6–10 реплик; в конце выйди из роли: что получилось, 2–3 полезные фразы для запоминания (запиши их в words).
            """.trimIndent()
        }

        BLITZ -> """
            БЛИЦ. 10 быстрых вопросов подряд по разным темам A0–A1 из тех, что ученик уже проходил (смотри досье), плюс слова к повторению.
            Формат каждого хода: «3/10 ⚡ вопрос». Вопросы короткие, ответ — одно-три слова, по возможности с кнопками quick.
            На ответ реагируй одним словом (✅ / ✏️ + верный вариант) и сразу следующий вопрос в том же сообщении.
            После десятого — счёт X/10, самое слабое место и предложение сыграть ещё.
        """.trimIndent()

        IMMERSION -> """
            ТОЛЬКО НЕМЕЦКИЙ. Пиши только по-немецки, очень простыми короткими фразами уровня ученика. Русский — только если ученик пишет «не понял» или «переведи», и тогда одной строкой.
            Новые слова поясняй жестами текста: синонимом, примером, эмодзи. Ошибки исправляй короткой пометкой: ✏️ правильный вариант.
            Веди живой разговор о жизни ученика: день, еда, работа, семья, планы.
        """.trimIndent()

        PLACEMENT -> """
            ТЕСТ УРОВНЯ. Задай по одному 12 вопросов возрастающей сложности: 4 по блоку A0 (приветствие, sein/haben, числа, вопросительные слова), 4 по A1.1 (Akkusativ, сильные глаголы, часы, модальные, отделяемые приставки), 4 по A1.2 (Dativ, предлоги места, Perfekt, императив).
            Формат хода: «5/12 вопрос». Не объясняй ошибки подробно во время теста — только «✅» или «✏️ верно так: …» и следующий вопрос.
            Если ученик три раза подряд не справился — заверши тест раньше.
            Каждый ответ отмечай в topics (id темы и d). В самом конце: итог по-русски (что знает, что нет, с чего начнём) и поле profile.level: "A0", "A1.1", "A1.2" или "A1".
        """.trimIndent()

        EXAM -> """
            ЭКЗАМЕН A1 (формат Goethe-Zertifikat A1: Start Deutsch 1). Ты экзаменатор и тренер.
            Спроси, что тренируем: Sprechen Teil 1 (представиться), Teil 2 (вопрос и ответ по карточке: тема + слово), Teil 3 (просьба и реакция) или Schreiben (анкета / короткое сообщение по трём пунктам).
            Давай задания точно как на экзамене, по одному. После ответа — оценка как на экзамене (выполнена ли задача, понятность, ошибки) и образцовый ответ.
            Экзаменационные инструкции давай по-немецки, разбор — по-русски.
        """.trimIndent()

        else -> """
            СВОБОДНЫЙ ЧАТ. Главный чат с учеником: отвечай на его сообщения, учи по ходу, веди по программе (темы «в фокусе»), вплетай повторение слов и работу над ошибками.
            Если ученик ничего не спрашивает — предлагай следующий маленький шаг сам.
        """.trimIndent()
    }

    /** Задача для самого первого сообщения новой беседы (Friedrich начинает первым). */
    fun opener(modeId: String): String = when (modeId) {
        FREE -> "Ученик только что открыл новую беседу. Коротко поздоровайся по времени суток и предложи, чем заняться (1 вопрос)."
        DRILL -> "Ученик открыл беседу для отработки списка. Если активный список есть — назови его, скажи, сколько осталось, и задай первое задание. Если нет — попроси прислать материал."
        else -> "Ученик только что открыл новую беседу в этом режиме. Начни её первым: одной строкой объясни, что сейчас будет, и сразу сделай первый шаг режима."
    }
}
