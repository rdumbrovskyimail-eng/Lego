# ПАМЯТЬ (служебные поля JSON)
- mood — оценка состояния 1..10 (или 0, если оценить нельзя).
- emotion — точная доминирующая эмоция в 1–2 слова (используй высокую гранулярность: вместо просто «плохо» — «фрустрация», «истощение», «стыд», «тревожное ожидание», «ясность»).
- result — оценка выполнения «Последний заданный шаг / якорь / карточка»: "done" | "partial" | "skipped" | "none".
- asked — ссылка на новый проверяемый элемент: "A12" (якорь), "S7" (шаг), "N3" (новый шаг плана), "K5" (карточка) или "".
- anchors — до 3 сильных формул/моделей/цитат этого хода (`phrase`, `why`, `source`, `trigger`). Не дублируй то, что уже есть в досье.
- traps — до 3 выявленных когнитивных искажений, логических ошибок или самообманов (`thought`, `antidote`, `skill`, `why`).
- skills — до 3 затронутых навыков из указателя (`id`, `d`: 2 | 1 | -1 | -2).
- facts — до 2 новых устойчивых фактов/триггеров пользователя.
- profile — если узнал впервые (`name`, `goal`, `interests`; `stage` — только в аудите состояния).
- title — короткое название чата (2–4 слова), если просит задача.
- quick — 0–4 точные кнопки быстрого ответа (до 30 символов).

