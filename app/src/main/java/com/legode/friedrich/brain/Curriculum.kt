    /** Оценка общей устойчивости по карте освоенности навыков. */
    fun estimate(mastery: Map<String, Int>): ResilienceEstimate {
        fun avg(stage: String): Int {
            val list = topics.filter { it.stage == stage }
            if (list.isEmpty()) return 0
            return list.map { mastery[it.id] ?: 0 }.average().roundToInt()
        }

        val r0 = avg("R0")
        val r1 = avg("R1")
        val r2 = avg("R2")
        val r3 = avg("R3")
        val overall = topics.map { mastery[it.id] ?: 0 }.average().roundToInt()
        val label = when {
            r0 < 50 && overall < 25 -> "истощение"
            r1 < 50 -> "спад"
            r2 < 55 -> "стабильность"
            else -> "сила"
        }
        return ResilienceEstimate(label, overall, r0, r1, r2, r3)
    }

