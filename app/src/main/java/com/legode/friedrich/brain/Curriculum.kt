    /** Протоколы, которых касается текст переписки, самые релевантные — первыми. */
    fun match(text: String, limit: Int): List<Topic> {
        val low = " " + Norm.normalizeYo(text.lowercase()) + " "
        if (low.isBlank()) return emptyList()
        return topics
            .map { t -> t to t.keywords.count { k -> low.contains(k) } }
            .filter { it.second > 0 }
            .sortedByDescending { it.second }
            .take(limit)
            .map { it.first }
    }

    /** Компактный указатель всех 60 навыков для системного контекста. */
    fun index(mastery: Map<String, Int>): String {
        val sb = StringBuilder()
        var lastStage = ""
        for (id in path) {
            val t = byId[id] ?: continue
            if (t.stage != lastStage) {
                if (sb.isNotEmpty()) sb.append('\n')
                sb.append("[").append(t.stage).append("] ")
                lastStage = t.stage
            } else {
                sb.append("; ")
            }
            sb.append(t.id).append(" = ").append(t.title).append(" (").append(mastery[t.id] ?: 0).append("%)")
        }
        return sb.toString()
    }

    fun sheetBlock(t: Topic): String = "### ${t.id} — ${t.title} (${t.school}) [${t.stage}]\n${t.sheet}"

    /** Полный методологический атлас для системного промпта (при включённом fullReference). */
    val fullReference: String by lazy {
