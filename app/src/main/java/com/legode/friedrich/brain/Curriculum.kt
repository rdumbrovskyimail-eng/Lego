    fun focus(mastery: Map<String, Int>, count: Int = 3): List<Topic> =
        path.mapNotNull { byId[it] }.filter { (mastery[it.id] ?: 0) < 70 }.take(count)

    /** Ближайшие интеллектуальные модели для прокачки (< 70%). */
    fun focusMental(mastery: Map<String, Int>, count: Int = 3): List<Topic> =
        topics.filter { it.stage.startsWith("M") && (mastery[it.id] ?: 0) < 70 }.take(count)

    /** Самые слабые навыки среди тех, которые уже практиковались. */
    fun weakest(mastery: Map<String, Int>, touched: Set<String>, count: Int = 3): List<Topic> =
        path.mapNotNull { byId[it] }
            .filter { it.id in touched && (mastery[it.id] ?: 0) < 60 }
            .sortedBy { mastery[it.id] ?: 0 }
            .take(count)

    /** Стартовая карта по самооценке при онбординге. */
    fun seedMastery(selfState: Int): Map<String, Int> {
        val out = HashMap<String, Int>()
        for (t in topics) {
            out[t.id] = when (selfState) {
                1 -> when (t.stage) {
                    "R0" -> 45
                    "R1", "M1" -> 25
                    else -> 5
                }

                2 -> when (t.stage) {
                    "R0" -> 70
                    "R1", "M1" -> 55
                    "R2", "M2" -> 35
                    else -> 15
                }

                else -> when (t.stage) {
                    "R0" -> 10
                    else -> 0
                }
            }
        }
        return out
    }
