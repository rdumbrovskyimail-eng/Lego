            .take(count)

    /** Стартовая карта по самооценке при онбординге: 0 — в яме/истощении, 1 — штормит, 2 — держусь, нужен прорыв. */
    fun seedMastery(selfState: Int): Map<String, Int> {
        val out = HashMap<String, Int>()
        for (t in topics) {
            out[t.id] = when (selfState) {
                1 -> when (t.stage) {
                    "R0" -> 45
                    "R1" -> 25
                    else -> 5
                }

                2 -> when (t.stage) {
                    "R0" -> 70
                    "R1" -> 55
                    "R2" -> 35
                    else -> 15
                }

                else -> when (t.stage) {
                    "R0" -> 10
                    else -> 0
                }
            }
        }
        return out
    }
