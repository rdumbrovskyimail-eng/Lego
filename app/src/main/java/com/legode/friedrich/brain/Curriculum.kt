    /** Оценка устойчивости и когнитивного уровня по карте освоенности навыков. */
    fun estimate(mastery: Map<String, Int>): ResilienceEstimate {
        fun avgStage(stage: String): Int {
            val list = topics.filter { it.stage == stage }
            if (list.isEmpty()) return 0
            return list.map { mastery[it.id] ?: 0 }.average().roundToInt()
        }

        val r0 = avgStage("R0")
        val r1 = avgStage("R1")
        val r2 = avgStage("R2")
        val r3 = avgStage("R3")
        val m1 = avgStage("M1")
        val m2 = avgStage("M2")
        val m3 = avgStage("M3")

        val psychTopics = topics.filter { it.stage.startsWith("R") }
        val intelTopics = topics.filter { it.stage.startsWith("M") }
        val psychOverall = if (psychTopics.isEmpty()) 0 else psychTopics.map { mastery[it.id] ?: 0 }.average().roundToInt()
        val intelOverall = if (intelTopics.isEmpty()) 0 else intelTopics.map { mastery[it.id] ?: 0 }.average().roundToInt()

        val label = when {
            r0 < 50 && psychOverall < 25 -> "истощение"
            r1 < 50 -> "спад"
            r2 < 55 -> "стабильность"
            else -> "сила"
        }
        return ResilienceEstimate(label, psychOverall, r0, r1, r2, r3, m1, m2, m3, intelOverall)
    }

    /** Баллы 6 осей для Радара развития (0..100). */
    fun radarScores(mastery: Map<String, Int>, brierAvg: Double = -1.0): RadarScores {
        fun avgBlocks(vararg blockIds: String): Int {
            val list = topics.filter { it.block in blockIds }
            if (list.isEmpty()) return 0
            return list.map { mastery[it.id] ?: 0 }.average().roundToInt()
        }

        val calTopicAvg = avgBlocks("decisions")
        val calFromBrier = if (brierAvg in 0.0..1.0) ((1.0 - (brierAvg / 0.35)).coerceIn(0.0, 1.0) * 100.0).roundToInt() else -1
        val calibration = if (calFromBrier >= 0) ((calTopicAvg * 0.4 + calFromBrier * 0.6).roundToInt()) else calTopicAvg

        return RadarScores(
            resilience = avgBlocks("body", "act", "stoic"),
            critical = avgBlocks("cbt", "critical"),
            systems = avgBlocks("systems", "meaning"),
            calibration = calibration,
            learning = avgBlocks("learning"),
            execution = avgBlocks("action", "strategy")
        )
    }

